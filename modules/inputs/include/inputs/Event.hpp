/**
 * @file Event.hpp
 * @brief Input event types, event queue, and event dispatcher for the
 *        ATOM input system.
 */

#ifndef ATOM_INPUT_EVENT_HPP
#define ATOM_INPUT_EVENT_HPP

#include "KeyCodes.hpp"

#include <cstddef>
#include <cstdint>
#include <functional>
#include <vector>

namespace Atom::Input
{

// ---------------------------------------------------------------------------
// EventType
// ---------------------------------------------------------------------------

/**
 * @brief Discriminator for the kind of input event.
 */
enum class EventType : uint8_t
{
    KeyDown,           ///< A key was pressed.
    KeyUp,             ///< A key was released.
    KeyRepeat,         ///< A key repeat was generated by the OS.
    MouseButtonDown,   ///< A mouse button was pressed.
    MouseButtonUp,     ///< A mouse button was released.
    MouseMove,         ///< The mouse cursor moved.
    MouseScroll,       ///< The mouse scroll wheel moved.
    WindowFocusGained, ///< The window gained input focus.
    WindowFocusLost,   ///< The window lost input focus.
    WindowResize,      ///< The window was resized.
    WindowClose,       ///< The window close was requested.
    Count              ///< Total number of event types (not a valid type).
};

/**
 * @brief Return a human-readable name for an event type.
 * @param type The event type to look up.
 * @return Null-terminated string such as "KeyDown". Never null.
 */
const char *eventTypeName(EventType type) noexcept;

// ---------------------------------------------------------------------------
// Event payload structs
// ---------------------------------------------------------------------------

/**
 * @brief Payload for keyboard events (KeyDown, KeyUp, KeyRepeat).
 */
struct KeyEventData
{
    KeyCode key;        ///< Which key was affected.
    bool isRepeat;      ///< True when the event is an OS key-repeat.
    uint16_t modifiers; ///< Active modifier flags (see Modifier).
};

/**
 * @brief Payload for mouse button events (MouseButtonDown, MouseButtonUp).
 */
struct MouseButtonEventData
{
    MouseButton button; ///< Which button was affected.
    int32_t x;          ///< Cursor X position at the time of the event.
    int32_t y;          ///< Cursor Y position at the time of the event.
    uint8_t clicks;     ///< Click count (1 = single, 2 = double, etc.).
};

/**
 * @brief Payload for mouse movement events.
 */
struct MouseMoveEventData
{
    int32_t x;      ///< New cursor X position.
    int32_t y;      ///< New cursor Y position.
    int32_t deltaX; ///< Horizontal movement since last event.
    int32_t deltaY; ///< Vertical movement since last event.
};

/**
 * @brief Payload for mouse scroll events.
 */
struct MouseScrollEventData
{
    float deltaX; ///< Horizontal scroll amount.
    float deltaY; ///< Vertical scroll amount.
};

/**
 * @brief Payload for window resize events.
 */
struct WindowResizeEventData
{
    int32_t width;  ///< New window width in pixels.
    int32_t height; ///< New window height in pixels.
};

// ---------------------------------------------------------------------------
// Event
// ---------------------------------------------------------------------------

/**
 * @brief A single input event.
 *
 * The active union member is determined by @c type.
 */
struct Event
{
    EventType type;       ///< Discriminator.
    uint64_t timestampMs; ///< Millisecond timestamp (origin is unspecified).

    union
    {
        KeyEventData key;                   ///< Valid when type is Key*.
        MouseButtonEventData mouseButton;   ///< Valid when type is MouseButton*.
        MouseMoveEventData mouseMove;       ///< Valid when type is MouseMove.
        MouseScrollEventData mouseScroll;   ///< Valid when type is MouseScroll.
        WindowResizeEventData windowResize; ///< Valid when type is WindowResize.
    };
};

// ---------------------------------------------------------------------------
// EventQueue
// ---------------------------------------------------------------------------

/**
 * @brief Lock-free-style circular buffer for input events.
 *
 * Capacity is always a power of two so that index wrapping can be done
 * with a bitmask instead of a modulo.
 */
class EventQueue
{
  public:
    /**
     * @brief Construct an event queue.
     * @param capacity Desired capacity (rounded up to the next power of 2).
     */
    explicit EventQueue(std::size_t capacity = 256);

    /**
     * @brief Push an event onto the back of the queue.
     * @param event The event to enqueue.
     * @return True if the event was stored, false if the queue was full.
     */
    bool push(const Event &event) noexcept;

    /**
     * @brief Pop the oldest event from the front of the queue.
     * @param event Receives the dequeued event on success.
     * @return True if an event was dequeued, false if the queue was empty.
     */
    bool pop(Event &event) noexcept;

    /**
     * @brief Peek at the oldest event without removing it.
     * @param event Receives a copy of the front event on success.
     * @return True if an event was available, false if the queue was empty.
     */
    bool peek(Event &event) const noexcept;

    /**
     * @brief Test whether the queue contains no events.
     * @return True if empty.
     */
    [[nodiscard]] bool isEmpty() const noexcept;

    /**
     * @brief Test whether the queue is at capacity.
     * @return True if full.
     */
    [[nodiscard]] bool isFull() const noexcept;

    /**
     * @brief Return the number of events currently stored.
     * @return Event count.
     */
    [[nodiscard]] std::size_t count() const noexcept;

    /**
     * @brief Discard all queued events.
     */
    void clear() noexcept;

  private:
    std::vector<Event> m_buffer; ///< Ring buffer storage.
    std::size_t m_capacity;      ///< Always a power of two.
    std::size_t m_head;          ///< Write position.
    std::size_t m_tail;          ///< Read position.
    std::size_t m_count;         ///< Number of stored events.
};

// ---------------------------------------------------------------------------
// EventDispatcher
// ---------------------------------------------------------------------------

/**
 * @brief Routes events to registered listener callbacks by event type.
 */
class EventDispatcher
{
  public:
    /// Signature of an event listener callback.
    using EventCallback = std::function<void(const Event &)>;

    /// Opaque handle returned by addListener, used to remove a listener.
    using ListenerID = uint32_t;

    /**
     * @brief Register a callback for a specific event type.
     * @param type  The event type to listen for.
     * @param callback  The function to call when a matching event arrives.
     * @return A unique listener identifier that can be passed to
     *         removeListener().
     */
    ListenerID addListener(EventType type, EventCallback callback);

    /**
     * @brief Remove a previously registered listener.
     * @param id The identifier returned by addListener().
     */
    void removeListener(ListenerID id);

    /**
     * @brief Dispatch an event to all listeners registered for its type.
     * @param event The event to dispatch.
     */
    void dispatch(const Event &event);

    /**
     * @brief Remove all registered listeners.
     */
    void clear();

  private:
    /// Internal record tying a listener id and type to its callback.
    struct ListenerEntry
    {
        ListenerID id;          ///< Unique identifier.
        EventType type;         ///< Event type filter.
        EventCallback callback; ///< User-provided callback.
    };

    std::vector<ListenerEntry> m_listeners; ///< All active listeners.
    ListenerID m_nextID = 1;                ///< Monotonic ID counter.
};

} // namespace Atom::Input

#endif // ATOM_INPUT_EVENT_HPP
